namespace Study3D.FpsGame.Weapon.Cards
{
    // 카드가 발동하는 시점 입니다. 카드 한 장은 이 중 하나의 시점에만 발동합니다.
    // - 같은 효과(폭발 등)도 어느 시점에 거느냐에 따라 동작이 달라지므로, 시점은 카드 에셋에서 고릅니다.
    public enum CardTiming
    {
        Shoot,   // 발사할 때 (분열된 자식이 생겨날 때 포함)
        Flying,  // 날아가는 동안 매 프레임
        Hit,     // 무언가에 부딪힐 때마다 (관통, 반사로 계속 날아가도 부딪힐 때마다 발동)
        Destroy, // 사라질 때 한 번 (멈춘 충돌, 수명 만료)
    }
}
