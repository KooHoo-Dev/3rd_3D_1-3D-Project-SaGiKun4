namespace Study3D.FpsGame.Weapon.Cards
{
    // 카드가 맡는 역할 입니다. 같은 시점의 카드들은 역할 순서(반응 → 조향 → 효과)대로 실행됩니다.
    // - 시점(CardTiming)이 "언제"라면, 역할은 "무엇을 결정하는가" 입니다.
    // - 같은 역할 안에서는 쌓은 순서대로 실행합니다.
    // - 값의 순서가 곧 실행 순서 입니다.
    public enum CardRole
    {
        Response, // 부딪힌 순간 운동량이 어떻게 되는가 (관통: 유지, 반사: 면 기준으로 꺾임). 한 충돌에 한 장만 결정합니다.
        Steer,    // 어디를 향해 가는가 (전이, 유도 등). 반응이 정해진 뒤 진행 방향을 고칩니다.
        Effect,   // 그 자리에서 무엇이 일어나는가 (폭발, 분열 등)
    }
}
